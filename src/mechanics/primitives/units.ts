/**
 * Unit conversions between internal combat storage and UI display.
 *
 * These helpers use SDK-normalized internal distance units: one internal unit
 * converts to ten display meters. This is a call-site conversion convention,
 * not a claim that every Unity world-space distance uses the same scale.
 * Impetus stores raw float; UI shows ÷100.
 */
/* ── file map ─────────────────────────────────────────────────────────────────
 * exports    internalDistanceToMeters, metersToInternalDistance, impetusToDisplayPerMeter, displayPerMeterToImpetus, DISTANCE_EPSILON_SQ
 * depends    —
 * used by    src/calculators/specs.generated, src/mechanics/combat/distances, src/mechanics/primitives/index
 * ─────────────────────────────────────────────── generated by `npm run map` ──
 */

/** SDK-normalized internal distance → display meters (×10). */
export function internalDistanceToMeters(internal: number): number {
  return internal * 10
}

/** Display meters → SDK-normalized internal distance (÷10). */
export function metersToInternalDistance(meters: number): number {
  return meters / 10
}

/** Raw impetus stat → UI "×/m" label. */
export function impetusToDisplayPerMeter(impetus: number): number {
  return impetus / 100
}

/** UI "×/m" → raw impetus stat. */
export function displayPerMeterToImpetus(display: number): number {
  return display * 100
}

/** Squared distance guard used in distance cache when center positions coincide. */
export const DISTANCE_EPSILON_SQ = 1e-4
