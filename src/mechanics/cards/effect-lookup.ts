/**
 * Card level / mastery effect lookup — values from `card-data.ts`.
 */
/* ── file map ─────────────────────────────────────────────────────────────────
 * exports    cardLevelMultiplier, cardLevelPercentFraction, cardMasteryPercentFraction, superTowerActiveDamageMultiplier, superTowerActiveUltimateDamageMultiplier, superTowerCycleTiming, enemyBalanceSpawnMultiplier, enemyBalanceMasteryDoubleSpawnChancePct
 * depends    src/data, src/mechanics/enemies/drops-shared
 * used by    src/calculators/specs.generated, src/mechanics/cards/index, src/mechanics/enemies/elite-spawn-chance
 * ─────────────────────────────────────────────── generated by `npm run map` ──
 */
import { CARD_TEMPLATE_MAP, computeLabValueAtLevel, findToolLabBySlug } from '../../data'
import { clampCardGameLevel, clampCardMasteryLevel } from '../enemies/drops-shared'

function cardLevelIndex(gameLevel: number): number {
  return clampCardGameLevel(gameLevel) - 1
}

/** Multiplier cards (e.g. Enemy Balance level → enemies spawned per wave). */
export function cardLevelMultiplier(cardId: string, gameLevel: number): number {
  const card = CARD_TEMPLATE_MAP[cardId]
  if (!card || card.levelType !== 'multi') return 1
  const raw = card.levelValues[cardLevelIndex(gameLevel)]
  return typeof raw === 'number' ? raw : 1
}

/** Percent cards (e.g. Wave Accelerator cooldown reduction) as 0–1 fraction. */
export function cardLevelPercentFraction(cardId: string, gameLevel: number): number {
  const card = CARD_TEMPLATE_MAP[cardId]
  if (!card || card.levelType !== 'percent') return 0
  const raw = card.levelValues[cardLevelIndex(gameLevel)]
  return typeof raw === 'number' ? raw / 100 : 0
}

/** Mastery percent values from card template (0–1 fraction). */
export function cardMasteryPercentFraction(cardId: string, masteryLevel: number): number {
  const card = CARD_TEMPLATE_MAP[cardId]
  if (!card?.masteryValues?.length) return 0
  const idx = clampCardMasteryLevel(masteryLevel)
  return card.masteryValues[idx] / 100
}

/** Card-catalog-derived Super Tower multiplier while active, including its Bonus lab; not native parity. */
export function superTowerActiveDamageMultiplier(gameLevel: number, bonusLabLevel = 0): number {
  if (!Number.isInteger(bonusLabLevel) || bonusLabLevel < 0) {
    throw new RangeError('Super Tower Bonus lab level must be a non-negative integer')
  }
  const lab = findToolLabBySlug('super_tower_bonus')
  if (!lab) throw new Error('Super Tower Bonus lab catalog required')
  return cardLevelMultiplier('st', gameLevel) * computeLabValueAtLevel(lab, bonusLabLevel)
}

/**
 * While Super Tower is active, Ultimate Tower transfers 35% of its multiplier
 * to ultimate weapons (current card mastery description). It transfers the
 * multiplier itself, not 35% of the bonus above 1. Mastery levels change timing.
 */
export function superTowerActiveUltimateDamageMultiplier(
  gameLevel: number, bonusLabLevel: number, hasMastery: boolean,
): number {
  return hasMastery ? 0.35 * superTowerActiveDamageMultiplier(gameLevel, bonusLabLevel) : 1
}

/**
 * Current catalog: 15 seconds active, then 30 seconds inactive before mastery.
 * Mastery subtracts its catalog duration from the inactive window. cycleSeconds
 * is start-to-start; this catalog model does not choose the first activation's
 * phase or assert native runtime parity.
 */
export function superTowerCycleTiming(hasMastery: boolean, masteryLevel = 0): {
  activeDurationSeconds: number; inactiveDurationSeconds: number; cycleSeconds: number
} {
  const card = CARD_TEMPLATE_MAP.st
  const reduction = hasMastery ? card.masteryValues?.[clampCardMasteryLevel(masteryLevel)] ?? 0 : 0
  const activeDurationSeconds = 15
  const inactiveDurationSeconds = Math.max(0, 30 - reduction)
  return { activeDurationSeconds, inactiveDurationSeconds,
    cycleSeconds: activeDurationSeconds + inactiveDurationSeconds }
}

/** Enemy Balance card level — increases enemies spawned each wave. */
export function enemyBalanceSpawnMultiplier(gameLevel: number): number {
  return cardLevelMultiplier('eb', gameLevel)
}

/** Enemy Balance mastery — chance for double elite spawn (0–100). */
export function enemyBalanceMasteryDoubleSpawnChancePct(masteryLevel: number): number {
  return cardMasteryPercentFraction('eb', masteryLevel) * 100
}
