const ASSIST_UNIQUE_RARITIES: readonly AssistUniqueEffectRarity[] = ['Epic', 'Legendary', 'Mythic', 'Ancestral']

/** Decode the exact assistModuleSlots[].uniqueEffectEfficiencyLevel field.
 * SDK knowledge/modules.ts owner chart (2026-08-17) identifies slot unlock as
 * Epic followed by three paid Legendary/Mythic/Ancestral upgrades. The current
 * official export stores the count separately from main/substat efficiencies.
 * Current player explanation: https://www.reddit.com/r/TheTowerGame/comments/1vrt7uk/ .
 * This is a source-qualified ordinal join, not a native-runtime parity claim.
 * Missing, malformed and unknown values return null without coercion.
 */
export function decodeAssistUniqueEffectLevel(raw: unknown): DecodedAssistUniqueEffectLevel | null {
  if (typeof raw !== 'number' || !Number.isInteger(raw) || raw < 0 || raw > 3) return null
  return { upgradeLevel: raw as 0 | 1 | 2 | 3, slotRarity: ASSIST_UNIQUE_RARITIES[raw]! }
}

/** The slot cannot promote the equipped module's own unique rarity. Plus/star
 * suffixes do not raise that coarse rung. Only SDK canonical labels are accepted.
 */
export function resolveAssistUniqueEffectRarity(raw: unknown, moduleRarityLabel: unknown): AssistUniqueEffectRarity | null {
  const slot = decodeAssistUniqueEffectLevel(raw)
  if (!slot || typeof moduleRarityLabel !== 'string' || !MODULE_RARITIES.some(label => label === moduleRarityLabel)) return null
  const coarse = moduleRarityLabel.split(' ')[0]
  const moduleRung = ASSIST_UNIQUE_RARITIES.findIndex(label => label === coarse)
  if (moduleRung < 0) return null
  return ASSIST_UNIQUE_RARITIES[Math.min(slot.upgradeLevel, moduleRung)]!
}